"""Shared helpers for ReactiveSessionActor tests.

Provides factory functions for creating mock objects used across
test_reactive_session_actor.py, test_actor_handlers.py,
test_actor_budget.py, and test_actor_integration.py.
"""

import asyncio
import uuid
from typing import Any, Dict, List, Optional, Union
from unittest.mock import AsyncMock, MagicMock

from src.ai_engine.intervention.types import (
    InterventionSignal,
    InterventionType,
)

_UNSET = object()  # sentinel for "not provided"


def _make_signal(
    signal_type: str = InterventionType.ADDITIVE.value,
    signal_id: Optional[str] = None,
    session_id: str = "test-session",
    job_id: str = "test-job",
    user_id: str = "test-user",
    payload: Optional[Dict[str, Any]] = None,
    priority: int = 2,
) -> InterventionSignal:
    """Create an InterventionSignal for testing."""
    return InterventionSignal(
        signal_id=signal_id or str(uuid.uuid4()),
        type=signal_type,
        session_id=session_id,
        job_id=job_id,
        user_id=user_id,
        timestamp="2026-02-21T00:00:00+00:00",
        payload=payload or {},
        priority=priority,
    )


def _make_pending_req(
    *,
    all_text: Optional[List[str]] = None,
    all_tool_calls: Optional[List[Dict[str, Any]]] = None,
    future: Union[asyncio.Future, object, None] = _UNSET,
    task: Optional[MagicMock] = None,
    user_id: str = "test-user",
    family_id: str = "test-family",
    session_id: str = "test-session",
    job_id: str = "test-job",
    route_type: str = "slow",
    user_input: Optional[str] = None,
    **overrides: Any,
) -> MagicMock:
    """Create a mock _StreamingRequest for testing.

    Builds a fully-populated mock with sane defaults for all attributes
    that ReactiveSessionActor inspects. Individual fields can be
    overridden via keyword arguments.
    """
    mock_task = task
    if mock_task is None:
        mock_task = MagicMock()
        mock_task.user_id = user_id
        mock_task.family_id = family_id
        mock_task.session_id = session_id
        mock_task.job_id = job_id
        mock_task.route_type = route_type
        if user_input is not None:
            mock_task.user_input = user_input

    mock_req = MagicMock()
    mock_req.task = mock_task
    mock_req.all_text = all_text if all_text is not None else []
    mock_req.all_tool_calls = all_tool_calls if all_tool_calls is not None else []
    mock_req.msg_count = overrides.pop("msg_count", 0)
    mock_req.last_msg_type = overrides.pop("last_msg_type", None)
    mock_req.stop_reason = overrides.pop("stop_reason", None)
    mock_req.turns_used = overrides.pop("turns_used", 0)
    mock_req.total_cost_usd = overrides.pop("total_cost_usd", None)
    mock_req.usage = overrides.pop("usage", None)
    mock_req.sdk_session_id = overrides.pop("sdk_session_id", None)
    # When future is not explicitly provided, leave it as a MagicMock
    # (auto-generated by MagicMock()) so .done() etc. work without errors.
    # Pass future=<real Future> to test actual future resolution logic.
    if future is not _UNSET:
        mock_req.future = future
    mock_req.sdk_stream_handler = MagicMock()
    mock_req.sdk_stream_handler.handle_sdk_message = AsyncMock()
    mock_req.sdk_stream_handler.emit_missing_thinking = AsyncMock()
    default_pubsub = MagicMock()
    default_pubsub.publish = AsyncMock()
    mock_req.pubsub = overrides.pop("pubsub", default_pubsub)
    mock_req.worker = overrides.pop("worker", MagicMock())
    mock_req.runner = overrides.pop("runner", MagicMock())
    mock_req.run_config = overrides.pop("run_config", MagicMock())
    mock_req.bridge = overrides.pop("bridge", MagicMock())
    mock_req.persistence = overrides.pop("persistence", MagicMock())
    mock_req.keepalive = overrides.pop("keepalive", MagicMock())
    mock_req.hook_builder = overrides.pop("hook_builder", MagicMock())
    mock_req.correction_resubmitted = overrides.pop("correction_resubmitted", False)

    # Apply any remaining overrides
    for key, value in overrides.items():
        setattr(mock_req, key, value)

    return mock_req
