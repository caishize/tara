"""T0 proactive triggers -- secretary initiates contact.

Scans for situations where the secretary should proactively reach out
to the user rather than waiting for a user request.

Four sub-scanners:
  1. approaching_date:    important dates within N days with no linked event
  2. cold_relationship:   members with low RelationshipThermometer score
  3. stale_commitment:    VAGUE/CONDITIONAL commitments past follow-up deadline
  4. user_rhythm:         placeholder for future user rhythm pattern matching

PLAN-003: E7-aware window uses per-date ``preparation_lead_days`` instead of
hardcoded 7 days.  Cross-scanner synthesis merges triggers for the same member.

V8 architecture: docs/architecture-v8-secretary-brain.md section 4.2
"""
import logging
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import Any, Dict, List, Optional
from uuid import UUID

from sqlalchemy import and_, func, select
from sqlalchemy.ext.asyncio import AsyncSession

from ....core.utils.timezone import utc_now
from .family_context import FamilyRelationContext

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Configuration constants
# ---------------------------------------------------------------------------

# Fallback days ahead when ImportantDate.preparation_lead_days is not set
APPROACHING_DATE_DAYS_DEFAULT = 7

# Maximum days to scan ahead (cap for per-date preparation_lead_days)
APPROACHING_DATE_MAX_HORIZON = 90

# Days since last interaction before a relationship is considered "cold"
COLD_RELATIONSHIP_DAYS = 30

# Maximum triggers per scan to avoid overwhelming the user
MAX_TRIGGERS_PER_SCAN = 10


# ---------------------------------------------------------------------------
# Trigger data class
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class ProactiveTrigger:
    """A proactive trigger generated by scanning family state.

    Attributes:
        trigger_type: Type of trigger discovered.
        family_id: Family the trigger belongs to.
        target_member_id: Optional member this trigger is about.
        data: Trigger-specific payload dict.
        priority: P0-P3 priority level.
    """

    trigger_type: str  # "approaching_date", "cold_relationship", "stale_commitment", "user_rhythm"
    family_id: UUID
    target_member_id: Optional[UUID] = None
    data: Dict[str, Any] = field(default_factory=dict)
    priority: str = "P2"


# ---------------------------------------------------------------------------
# ProactiveTriggerer
# ---------------------------------------------------------------------------

class ProactiveTriggerer:
    """Scans family state and produces proactive triggers.

    Each sub-scanner is isolated and handles its own errors so that a
    failure in one scanner does not block the others.

    PLAN-003: Accepts ``FamilyRelationContext`` for intimacy-aware priority.
    Cross-scanner synthesis merges overlapping triggers for the same member.
    """

    def __init__(self, db: AsyncSession):
        self._db = db

    async def scan_for_triggers(
        self,
        family_id: UUID,
        family_ctx: Optional[FamilyRelationContext] = None,
    ) -> List[ProactiveTrigger]:
        """Run all sub-scanners, synthesize, and collect triggers.

        Returns at most MAX_TRIGGERS_PER_SCAN triggers, sorted by priority.
        """
        triggers: List[ProactiveTrigger] = []

        for scanner in (
            self._scan_approaching_dates,
            self._scan_cold_relationships,
            self._scan_stale_commitments,
            self._scan_user_rhythm,
        ):
            try:
                found = await scanner(family_id, family_ctx=family_ctx)
                triggers.extend(found)
            except Exception:
                logger.warning(
                    "Proactive scanner %s failed for family %s",
                    scanner.__name__, family_id,
                    exc_info=True,
                )

        # PLAN-003: Synthesize triggers for the same member (TC-5)
        triggers = self._synthesize_triggers(triggers)

        # Sort: P0 > P1 > P2 > P3
        priority_order = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}
        triggers.sort(key=lambda t: priority_order.get(t.priority, 9))

        return triggers[:MAX_TRIGGERS_PER_SCAN]

    @staticmethod
    def _synthesize_triggers(
        triggers: List[ProactiveTrigger],
    ) -> List[ProactiveTrigger]:
        """Merge triggers for the same target_member_id (TC-5).

        When 2+ triggers target the same member, create a single "family_focus"
        trigger combining data from all constituent triggers, using the highest
        priority among them.  Template-based narrative (no LLM, per OQ-1).
        """
        if len(triggers) <= 1:
            return triggers

        # Group by target_member_id
        by_member: Dict[Optional[UUID], List[ProactiveTrigger]] = defaultdict(list)
        for t in triggers:
            by_member[t.target_member_id].append(t)

        result: List[ProactiveTrigger] = []
        priority_rank = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}

        for member_id, group in by_member.items():
            if member_id is None or len(group) < 2:
                # No merge for triggers without member or single triggers
                result.extend(group)
                continue

            # Pick highest priority
            best_priority = min(
                group, key=lambda t: priority_rank.get(t.priority, 9),
            ).priority

            # Merge data payloads
            merged_data: Dict[str, Any] = {
                "constituent_triggers": [
                    {"type": t.trigger_type, "priority": t.priority, **t.data}
                    for t in group
                ],
                "trigger_types": sorted(set(t.trigger_type for t in group)),
                "member_name": next(
                    (t.data.get("member_name") or t.data.get("title", "")
                     for t in group if t.data.get("member_name") or t.data.get("title")),
                    "",
                ),
            }

            # Template-based narrative
            merged_data["narrative"] = _build_synthesis_narrative(
                merged_data["member_name"],
                merged_data["trigger_types"],
                group,
            )

            result.append(ProactiveTrigger(
                trigger_type="family_focus",
                family_id=group[0].family_id,
                target_member_id=member_id,
                data=merged_data,
                priority=best_priority,
            ))

        return result

    # ------------------------------------------------------------------
    # Sub-scanner 1: Approaching important dates
    # ------------------------------------------------------------------

    async def _scan_approaching_dates(
        self,
        family_id: UUID,
        family_ctx: Optional[FamilyRelationContext] = None,
    ) -> List[ProactiveTrigger]:
        """Find important dates within their preparation window that have no linked curated event.

        PLAN-003 (TC-4): Uses per-date ``preparation_lead_days`` from ImportantDate
        instead of the former hardcoded 7-day window.  The DB query uses the
        maximum horizon (APPROACHING_DATE_MAX_HORIZON) and then each date is
        filtered by its specific lead.
        """
        from ...date_manager.date_models import ImportantDate
        from ..models import CuratedEvent

        now = utc_now()
        today = now.date()
        horizon = today + timedelta(days=APPROACHING_DATE_MAX_HORIZON)

        # Get upcoming important dates within max horizon
        stmt = (
            select(ImportantDate)
            .where(
                and_(
                    ImportantDate.family_id == family_id,
                    ImportantDate.solar_date >= today,
                    ImportantDate.solar_date <= horizon,
                )
            )
            .order_by(ImportantDate.solar_date.asc())
            .limit(20)
        )
        result = await self._db.execute(stmt)
        upcoming_dates = list(result.scalars().all())

        if not upcoming_dates:
            return []

        triggers: List[ProactiveTrigger] = []

        for imp_date in upcoming_dates:
            # E7: Use per-date preparation_lead_days; fallback to default
            lead_days = getattr(imp_date, "preparation_lead_days", None)
            if not isinstance(lead_days, int) or lead_days <= 0:
                lead_days = APPROACHING_DATE_DAYS_DEFAULT
            else:
                lead_days = max(lead_days, APPROACHING_DATE_DAYS_DEFAULT)

            days_until = (imp_date.solar_date - today).days

            # Skip dates outside their specific preparation window
            if days_until > lead_days:
                continue

            # Check if a curated event already covers this date
            # PLAN-003: Don't suppress when only placeholder events exist
            day_start = datetime.combine(imp_date.solar_date, datetime.min.time())
            day_end = datetime.combine(imp_date.solar_date, datetime.max.time())

            event_stmt = select(func.count(CuratedEvent.id)).where(
                and_(
                    CuratedEvent.family_id == family_id,
                    CuratedEvent.is_active.is_(True),
                    CuratedEvent.normalized_start <= day_end,
                    CuratedEvent.normalized_end >= day_start,
                    CuratedEvent.status != "placeholder",
                )
            )
            event_result = await self._db.execute(event_stmt)
            existing_count = event_result.scalar() or 0

            if existing_count == 0:
                # Determine priority based on days_until and intimacy
                priority = "P2"
                if days_until <= 3:
                    priority = "P1"

                # PLAN-003: Intimate member's date within lead window -> P0
                if family_ctx is not None and imp_date.member_id is not None:
                    if family_ctx.is_intimate(imp_date.member_id):
                        priority = "P0" if days_until <= 7 else "P1"

                triggers.append(ProactiveTrigger(
                    trigger_type="approaching_date",
                    family_id=family_id,
                    target_member_id=imp_date.member_id,
                    data={
                        "date_id": str(imp_date.id),
                        "title": imp_date.title,
                        "date_type": imp_date.date_type,
                        "solar_date": imp_date.solar_date.isoformat(),
                        "days_until": days_until,
                        "preparation_lead_days": lead_days,
                    },
                    priority=priority,
                ))

        return triggers

    # ------------------------------------------------------------------
    # Sub-scanner 2: Cold relationships
    # ------------------------------------------------------------------

    async def _scan_cold_relationships(
        self,
        family_id: UUID,
        family_ctx: Optional[FamilyRelationContext] = None,
    ) -> List[ProactiveTrigger]:
        """Find members with low RelationshipThermometer composite score."""
        from ...member.models.member import Member
        from ...relationship.thermometer import compute_temperature

        stmt = (
            select(Member)
            .where(
                and_(
                    Member.family_id == family_id,
                    Member.is_deleted.is_(False),
                )
            )
            .limit(50)
        )
        result = await self._db.execute(stmt)
        members = list(result.scalars().all())

        if not members:
            return []

        triggers: List[ProactiveTrigger] = []

        for member in members:
            try:
                temp = await compute_temperature(
                    user_id=member.created_by,
                    target_member_id=member.id,
                    db=self._db,
                )
                if temp.status in ("cold", "frozen"):
                    priority = "P1" if temp.status == "frozen" else "P2"
                    triggers.append(ProactiveTrigger(
                        trigger_type="cold_relationship",
                        family_id=family_id,
                        target_member_id=member.id,
                        data={
                            "member_name": member.name,
                            "temperature_status": temp.status,
                            "composite_score": round(temp.composite, 3),
                        },
                        priority=priority,
                    ))
            except Exception:
                logger.debug(
                    "Failed to compute temperature for member %s",
                    member.id,
                    exc_info=True,
                )

        return triggers

    # ------------------------------------------------------------------
    # Sub-scanner 3: Stale commitments
    # ------------------------------------------------------------------

    async def _scan_stale_commitments(
        self,
        family_id: UUID,
        family_ctx: Optional[FamilyRelationContext] = None,
    ) -> List[ProactiveTrigger]:
        """Find VAGUE/CONDITIONAL commitments that are past their follow-up deadline."""
        from ...memory.commitment_models import CommitmentItemRecord

        now = utc_now()

        stmt = (
            select(CommitmentItemRecord)
            .where(
                and_(
                    CommitmentItemRecord.family_id == family_id,
                    CommitmentItemRecord.status == "pending",
                    CommitmentItemRecord.commitment_type.in_(["vague", "conditional"]),
                    CommitmentItemRecord.next_follow_up_at <= now,
                )
            )
            .order_by(CommitmentItemRecord.next_follow_up_at.asc())
            .limit(20)
        )
        result = await self._db.execute(stmt)
        stale = list(result.scalars().all())

        triggers: List[ProactiveTrigger] = []

        for commitment in stale:
            days_overdue = 0
            if commitment.next_follow_up_at:
                days_overdue = (now - commitment.next_follow_up_at).days

            priority = "P1" if days_overdue >= 7 else "P2"
            triggers.append(ProactiveTrigger(
                trigger_type="stale_commitment",
                family_id=family_id,
                data={
                    "commitment_id": str(commitment.id),
                    "who": commitment.who,
                    "what": commitment.what,
                    "to_whom": commitment.to_whom,
                    "commitment_type": commitment.commitment_type,
                    "days_overdue": days_overdue,
                    "follow_up_count": commitment.follow_up_count or 0,
                },
                priority=priority,
            ))

        return triggers

    # ------------------------------------------------------------------
    # Sub-scanner 4: User rhythm
    # ------------------------------------------------------------------

    # Minimum messages across 14 days to consider a rhythm meaningful
    _RHYTHM_MIN_TOTAL_MESSAGES = 5
    # Minimum messages at a single hour to consider it a peak
    _RHYTHM_MIN_PEAK_MESSAGES = 3
    # How many top peak hours to track
    _RHYTHM_TOP_PEAKS = 2
    # How many days of history to analyse
    _RHYTHM_LOOKBACK_DAYS = 14
    # Tolerance window: trigger only after peak_hour + this many hours
    _RHYTHM_TOLERANCE_HOURS = 1

    async def _scan_user_rhythm(
        self,
        family_id: UUID,
        family_ctx: Optional[FamilyRelationContext] = None,
    ) -> List[ProactiveTrigger]:
        """Detect user's typical check-in hours and trigger if they missed one today.

        Algorithm:
        1. Query user-role messages from the past 14 days for this family.
        2. Group by hour-of-day (UTC) to build an interaction histogram.
        3. Pick the top 2 peak hours (minimum 3 messages each).
        4. For each peak hour, if current UTC hour is past peak + 1 h tolerance
           and no user message exists today at or after that peak hour, emit a
           check-in trigger.
        """
        from ...conversation.models import (
            AssistantChatSession,
            ConversationMessage,
        )

        now = utc_now()
        lookback_start = now - timedelta(days=self._RHYTHM_LOOKBACK_DAYS)
        today_start = now.replace(hour=0, minute=0, second=0, microsecond=0)

        # ---- Step 1: Build hour-of-day histogram over the lookback window ----
        hour_expr = func.extract("hour", ConversationMessage.created_at)
        histogram_stmt = (
            select(
                hour_expr.label("hour"),
                func.count().label("cnt"),
            )
            .select_from(ConversationMessage)
            .join(
                AssistantChatSession,
                AssistantChatSession.id == ConversationMessage.session_id,
            )
            .where(
                and_(
                    AssistantChatSession.family_id == family_id,
                    ConversationMessage.role == "user",
                    ConversationMessage.created_at >= lookback_start,
                )
            )
            .group_by(hour_expr)
            .order_by(func.count().desc())
        )
        result = await self._db.execute(histogram_stmt)
        rows = result.all()

        if not rows:
            return []

        total_messages = sum(r.cnt for r in rows)
        if total_messages < self._RHYTHM_MIN_TOTAL_MESSAGES:
            return []

        # Pick top N peak hours that exceed minimum threshold
        peak_hours = [
            (int(r.hour), int(r.cnt))
            for r in rows[:self._RHYTHM_TOP_PEAKS]
            if r.cnt >= self._RHYTHM_MIN_PEAK_MESSAGES
        ]

        if not peak_hours:
            return []

        # ---- Step 2: Check today's activity per peak hour ----
        current_hour = now.hour
        triggers: List[ProactiveTrigger] = []

        for peak_hour, peak_count in peak_hours:
            # Only trigger if we're past the peak hour + tolerance
            trigger_after = peak_hour + self._RHYTHM_TOLERANCE_HOURS
            if current_hour < trigger_after:
                continue

            # Check if there is any user message today at or after peak_hour
            today_peak_start = today_start.replace(hour=peak_hour)
            today_check_stmt = (
                select(func.count())
                .select_from(ConversationMessage)
                .join(
                    AssistantChatSession,
                    AssistantChatSession.id == ConversationMessage.session_id,
                )
                .where(
                    and_(
                        AssistantChatSession.family_id == family_id,
                        ConversationMessage.role == "user",
                        ConversationMessage.created_at >= today_peak_start,
                        ConversationMessage.created_at < now,
                    )
                )
            )
            today_result = await self._db.execute(today_check_stmt)
            today_count = today_result.scalar() or 0

            if today_count == 0:
                triggers.append(ProactiveTrigger(
                    trigger_type="user_rhythm",
                    family_id=family_id,
                    data={
                        "peak_hour_utc": peak_hour,
                        "messages_at_peak": peak_count,
                        "lookback_days": self._RHYTHM_LOOKBACK_DAYS,
                        "total_messages_in_window": total_messages,
                        "current_hour_utc": current_hour,
                    },
                    priority="P3",
                ))

        return triggers


# ---------------------------------------------------------------------------
# Synthesis narrative templates (PLAN-003, OQ-1: template-based, no LLM)
# ---------------------------------------------------------------------------

def _build_synthesis_narrative(
    member_name: str,
    trigger_types: List[str],
    triggers: List[ProactiveTrigger],
) -> str:
    """Build a human-readable synthesis narrative from merged triggers.

    Uses pre-defined templates per trigger-type combination.
    """
    type_set = set(trigger_types)
    name = member_name or "这位家人"

    if {"approaching_date", "cold_relationship"} <= type_set:
        # Find the approaching date title
        date_title = ""
        for t in triggers:
            if t.trigger_type == "approaching_date":
                date_title = t.data.get("title", "")
                break
        if date_title:
            return f"{name}的{date_title}快到了，而且好久没联系了，这周重点关注一下"
        return f"{name}有重要日子快到了，而且好久没联系了，这周重点关注一下"

    if {"approaching_date", "stale_commitment"} <= type_set:
        return f"{name}有重要日子快到了，之前的承诺也该跟进了"

    if {"cold_relationship", "stale_commitment"} <= type_set:
        return f"好久没联系{name}了，之前的承诺也该兑现了"

    # Generic multi-trigger synthesis
    return f"{name}最近有几件事需要关注，建议统一安排一下"
